"""ШИМ моторов — RPi.GPIO (программный PWM на пинах EN драйвера L298N).

pigpio-бэкенд убран в v1.6.7: отдельный демон pigpiod и зависимость себя
не окупили (на рабочих скоростях робота дрожание скважности под нагрузкой
CPU незаметно, а RPi.GPIO не требует демона и работает на Pi 5 тоже).
Интерфейс make_pwm сохранён для совместимости вызовов motors.py/тестов.
"""


def make_pwm(gpio, pin, freq):
    """(pwm, имя_бэкенда). pwm ещё не запущен (вызовите .start(0))."""
    return gpio.PWM(pin, freq), 'rpigpio'
